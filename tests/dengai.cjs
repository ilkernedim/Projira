const assert = require('node:assert/strict');
const { analizEt, oneriBul, senaryoKur } = require('../node_modules/.tmp/dengai-tests/lib/dengai.js');
const { ornekPano, ornekSprintler } = require('../node_modules/.tmp/dengai-tests/data/seed.js');
const board = ornekPano();
const history = ornekSprintler();
const date = new Date(2026, 9, 26);
const base = analizEt(board, history, date);
const sum = a => a.uyeler.reduce((n,u) => n + u.atanan, 0);
const original = JSON.stringify(board);
const source = base.uyeler[0];
const transfer = senaryoKur(base, {}, 'zeynep', 0, source.uye.id, 'zeynep', 10000);
assert.equal(transfer.aktarilan, source.atanan);
assert.equal(sum(analizEt(board, history, date, transfer.ekstra)), sum(base));
assert.equal(senaryoKur(base, {}, 'zeynep', 0, 'elif', 'elif', 10).aktarilan, 0);
const added = senaryoKur(base, {}, 'zeynep', 57, 'elif', 'zeynep', 10);
assert.equal(sum(analizEt(board, history, date, added.ekstra)), sum(base) + 57);
assert.deepEqual(senaryoKur(base, {}, 'zeynep', NaN, 'elif', 'zeynep', Infinity).ekstra, {});
const suggestion = oneriBul(board, history, date);
assert.ok(suggestion, 'Örnek panoda iyileştirme bulunmalı');
assert.equal(Object.keys(suggestion.ekstra).length, 2);
assert.equal(suggestion.ekstra[suggestion.kimden.uye.id], -suggestion.saat);
assert.equal(suggestion.ekstra[suggestion.kime.uye.id], suggestion.saat);
assert.equal(sum(suggestion.yeni), sum(base));
assert.ok(suggestion.kazancGun > 0);
assert.equal(JSON.stringify(board), original, 'Analiz panoyu değiştirmemeli');
const empty = ornekPano();
for (const column of Object.values(empty.columns)) column.taskIds = [];
assert.equal(oneriBul(empty, history, date), null);
assert.equal(senaryoKur(analizEt(empty, history, date), {}, 'zeynep', 0, 'elif', 'zeynep', 10).aktarilan, 0);
console.log('Geçti: iş korunumu, aktarım sınırı, aynı kişi, yeni iş, geçersiz sayı, öneri tutarlılığı, boş pano ve değişmezlik.');
assert.equal(Object.keys(board.tasks).length, 6);
assert.equal(history.length, 3);
assert.equal(base.uyeler.length, 3);
const legacy = structuredClone(board);
legacy.tasks.legacy = { ...Object.values(board.tasks)[0], id:'legacy', assignee:{id:'can',name:'Can'}, estimatedTime:10, loggedTime:0 };
legacy.columns.todo.taskIds.push('legacy');
const legacyAnalysis = analizEt(legacy, history, date);
assert.equal(legacyAnalysis.uyeler.find(u=>u.uye.id==='can').atanan,10);
assert.equal(sum(legacyAnalysis),sum(base)+10);
console.log('Sade örnek: 3 kişi, 6 görev, 3 sprint. Eski ekip kayıtları analizde korunuyor.');
